"""Built-in MCP servers — OpenWorker's first "preinstalled plugins".

These are the MCP servers that ship with OpenWorker and should be present (and
connectable) the moment the app opens — without the user hand-editing
`~/.config/coworker/mcp.json`. They are normal stdio MCP servers run as
``python -m <module>``; the trick is that ``command``/``cwd`` are derived from the
*current* interpreter and package root at seed time (``render_builtin``), so the
entry never hard-codes a stale venv path and survives a move / reinstall.

Seeding is idempotent and non-destructive:
  * a missing builtin is written (never clobbers user-added servers),
  * an existing builtin (matched by its ``-m <module>`` args) with a drifted
    command/cwd is repaired — only the autogenerated path fields change, all
    other fields (``enabled``, ``requires_approval``, ``env``, ``auth``,
    ``include_tools`` …) are preserved,
  * a same-named server whose args point at a different module is left alone.

``ensure_builtin_servers`` is called once at server startup (``run.py``); it is the
single bootstrap point for the preinstalled-plugin set.
"""

from __future__ import annotations

import importlib.resources
import sys
from pathlib import Path
from typing import Any, Optional

from .config import _write_global, read_global

# Built-in MCP servers shipped with OpenWorker. `module` is run as `-m <module>`
# under the current interpreter. `requires_approval` defaults False for our own
# trusted, read-oriented servers (mirrors the hand-written mcp.json).
BUILTIN_SERVERS: dict[str, dict[str, Any]] = {
    "novel-memory": {"module": "deskmate.novel_memory.server", "requires_approval": False},
    "perception": {"module": "deskmate.perception.server", "requires_approval": False},
    "deskmate-memory": {"module": "deskmate.memory.server", "requires_approval": False},
    "deskmate-proactivity": {"module": "deskmate.proactivity.server", "requires_approval": False},
    "deskmate-skills": {"module": "deskmate.skills.server", "requires_approval": False},
}

# Marker stamped onto autogenerated builtin entries so we can tell "our server"
# apart from a user's same-named custom server when repairing path drift.
_BUILTIN_MARKER = "_builtin"


def _package_root() -> Path:
    """Directory the `-m` entries should use as cwd (the repo / install root)."""
    try:
        return Path(importlib.resources.files("deskmate")).parent
    except Exception:
        # Fallback: this file lives at <root>/coworker/mcp/builtin.py.
        return Path(__file__).resolve().parents[2]


def render_builtin(name: str, cfg: dict[str, Any]) -> dict[str, Any]:
    """Build the concrete mcp.json entry for a builtin server using the *current*
    interpreter and package root — never a stale absolute path."""
    return {
        "command": sys.executable,
        "args": ["-m", cfg["module"]],
        "cwd": str(_package_root()),
        "enabled": True,
        "requires_approval": bool(cfg.get("requires_approval", False)),
        _BUILTIN_MARKER: True,
    }


def _builtin_module_of(existing: dict[str, Any]) -> Optional[str]:
    """If `existing` is one of our builtins (matched by its `-m <module>` args),
    return its name; else None. This also migrates the legacy hand-written
    entries, which lacked the `_builtin` marker."""
    args = existing.get("args")
    for name, cfg in BUILTIN_SERVERS.items():
        if args == ["-m", cfg["module"]]:
            return name
    return None


def ensure_builtin_servers(*, force: bool = False) -> list[str]:
    """Seed / repair the global mcp.json's builtin servers. Returns the names
    touched. A second call with no drift is a no-op.

    Safe to call at startup: never raises on I/O failure paths that would block
    the app (the caller in ``run.py`` also guards), but writes are atomic via
    ``_write_global``.
    """
    servers = read_global()
    touched: list[str] = []
    for name, cfg in BUILTIN_SERVERS.items():
        rendered = render_builtin(name, cfg)
        existing = servers.get(name)
        if existing is None:
            # Missing (never seeded) → add. Idempotent across versions.
            servers[name] = rendered
            touched.append(name)
            continue
        # Name exists: repair only if it's actually one of our builtins.
        if _builtin_module_of(existing) is None:
            continue  # user's custom same-named server — leave it alone
        drifted = (
            force
            or existing.get("command") != rendered["command"]
            or existing.get("cwd") != rendered["cwd"]
            or existing.get("args") != rendered["args"]
        )
        marker_missing = not existing.get(_BUILTIN_MARKER)
        if drifted or marker_missing:
            # Refresh only the autogenerated path fields; preserve user edits.
            # A legacy (pre-marker) entry with no path drift still gets the
            # marker stamped so migration is consistent.
            merged = dict(existing)
            merged["command"] = rendered["command"]
            merged["cwd"] = rendered["cwd"]
            merged["args"] = rendered["args"]
            merged[_BUILTIN_MARKER] = True
            servers[name] = merged
            touched.append(name)
    if touched:
        _write_global(servers)
    return touched
