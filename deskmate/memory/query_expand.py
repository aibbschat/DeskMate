"""P2-2 向量检索审计的落地改进——查询扩展（别名桥接）。

审计结论（见 docs/向量检索审计.md）：仓库当前**无任何向量索引**（无 vectors.json，
``vault_store.search`` 是逐文件子串扫描，连 FTS5 都没用上），所有记忆检索是纯关键词匹配。
8.1 评测集虽 100% 通过，但仅覆盖「显式命中」；文档 P08 暴露的**隐式查询缺口**
（用户问「成化年间的制度」但记忆里写的是「明朝」）关键词检索无法桥接。

本模块在**不伪造向量库**的前提下，给关键词检索加一层**确定性别名扩展**，
把「年号 ↔ 朝代」「庙号 ↔ 朝代」等强关联词打通，直接封堵 P08 缺口：
- 问「成化」→ 扩展出「明朝/宪宗/成化年间」→ 命中记忆里的「明朝」
- 问「明朝」→ 扩展出「朱明/大明/明代」+ 各年号 → 命中年号记忆

设计原则（与全局一致）：
- **零 LLM**：纯静态别名表，成本可忽略、可复现、可单测。
- **fail-open**：扩展失败返回原关键词，绝不阻断检索。
- **保守**：只在命中已知别名时扩展，不臆造；扩展后关键词总数封顶，避免噪声膨胀。
- **可观测**：``EXPANSION_MAP`` 集中维护，便于审计与增补。
"""

from __future__ import annotations

# 别名扩展表：键为用户输入可能的说法，值为应一并检索的关联词。
